"""Read feedback, redact it, classify it, and emit CANDIDATE regression cases.

Nothing in this module calls a model. Everything is reproducible offline.
The output is a list of review candidates, NOT an evaluation set: a case only
becomes part of an eval set after a human accepts it (see ANNOTATION_GUIDE.md).
"""

from __future__ import annotations

import csv
import json
from collections import Counter
from dataclasses import dataclass
from datetime import datetime, timezone
from pathlib import Path

from .redact import redact
from .taxonomy import FAILURE_MODES, TAXONOMY_VERSION, find_hits, modes

SCHEMA_VERSION = "0.1"

DISCLAIMER = (
    "Every case below is an UNREVIEWED CANDIDATE generated by deterministic "
    "rules. It is not a labelled example and must not be used to report "
    "accuracy, precision, recall, or fix rate. Human review is required."
)

SYNTHETIC_WARNING = (
    "This dataset is FABRICATED and exists only to demonstrate the pipeline. "
    "Any result computed from it is a demo artefact, never evidence."
)

PROVENANCE_WARNING = (
    "Dataset provenance was not declared. Re-run with --synthetic for fabricated "
    "data, or --real for a corpus whose licence and consent you have checked."
)


@dataclass(frozen=True)
class FeedbackRecord:
    id: str
    text: str
    source: str = "unspecified"
    product: str = ""
    version: str = ""


def _pick(row: dict, *names: str, default: str = "") -> str:
    for name in names:
        value = row.get(name)
        if value:
            return str(value)
    return default


def load_records(path: str | Path) -> list[FeedbackRecord]:
    """Load .jsonl or .csv. Rows without text are skipped, never guessed."""
    path = Path(path)
    if not path.exists():
        raise FileNotFoundError(f"input not found: {path}")
    suffix = path.suffix.lower()
    if suffix == ".jsonl":
        rows = []
        with path.open("r", encoding="utf-8") as handle:
            for line_no, line in enumerate(handle, 1):
                line = line.strip()
                if not line or line.startswith("//"):
                    continue
                try:
                    rows.append(json.loads(line))
                except json.JSONDecodeError as exc:
                    raise ValueError(f"{path}:{line_no}: invalid JSON: {exc}") from exc
    elif suffix == ".csv":
        with path.open("r", encoding="utf-8-sig", newline="") as handle:
            rows = list(csv.DictReader(handle))
    else:
        raise ValueError(f"unsupported input type: {suffix} (use .jsonl or .csv)")

    records: list[FeedbackRecord] = []
    for index, row in enumerate(rows, 1):
        text = _pick(row, "text", "feedback", "body", "content", "comment")
        if not text.strip():
            continue
        records.append(
            FeedbackRecord(
                id=_pick(row, "id", "record_id", default=f"row-{index:04d}"),
                text=text,
                source=_pick(row, "source", default="unspecified"),
                product=_pick(row, "product"),
                version=_pick(row, "version"),
            )
        )
    return records


def _normalize(text: str) -> str:
    return " ".join(text.lower().split())


def case_key(failure_mode: str, quote: str) -> str:
    """Stable identity for diffing two runs, independent of generated ids."""
    return f"{failure_mode}|{_normalize(quote)}"


def analyze(
    records: list[FeedbackRecord],
    *,
    dataset_label: str = "unnamed",
    synthetic: bool | None = None,
    run_id: str | None = None,
) -> dict:
    findings: list[dict] = []
    cases: list[dict] = []
    redactions: Counter[str] = Counter()
    counts: Counter[str] = Counter({mode: 0 for mode in modes()})

    for record in records:
        clean_text, hits_count = redact(record.text)
        for kind, n in hits_count.items():
            redactions[kind] += n
        for hit in find_hits(clean_text):
            finding_id = f"f-{len(findings) + 1:04d}"
            case_id = f"cte-{len(cases) + 1:04d}"
            key = case_key(hit.mode, hit.quote)
            finding = {
                "id": finding_id,
                "record_id": record.id,
                "source": record.source,
                "product": record.product,
                "version": record.version,
                "failure_mode": hit.mode,
                "matched_phrase": hit.phrase,
                "strength": hit.strength,
                "evidence": {
                    "quote": hit.quote,
                    "start": hit.start,
                    "end": hit.end,
                    "offsets_refer_to": "redacted text",
                },
                "key": key,
                "status": "candidate",
            }
            findings.append(finding)
            counts[hit.mode] += 1
            cases.append(
                {
                    "id": case_id,
                    "finding_id": finding_id,
                    "key": key,
                    "failure_mode": hit.mode,
                    "input": hit.quote,
                    "assertion": {
                        "type": "must_not_reproduce_failure_mode",
                        "value": hit.mode,
                        "description": FAILURE_MODES[hit.mode],
                    },
                    "evidence_record_id": record.id,
                    "status": "candidate",
                    "human_review_required": True,
                    "review": None,
                }
            )

    if synthetic is True:
        provenance = "synthetic"
    elif synthetic is False:
        provenance = "declared-real"
    else:
        provenance = "unspecified"

    warnings: list[str] = [DISCLAIMER]
    if synthetic is True:
        warnings.append(SYNTHETIC_WARNING)
    elif synthetic is None:
        warnings.append(PROVENANCE_WARNING)

    return {
        "schema_version": SCHEMA_VERSION,
        "tool": "complaint-to-eval",
        "taxonomy_version": TAXONOMY_VERSION,
        "run_id": run_id or datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "dataset": {
            "label": dataset_label,
            "provenance": provenance,
            "records": len(records),
        },
        "honesty": {
            "candidate_cases": len(cases),
            "accepted_cases": 0,
            "note": "No human labels exist yet. accepted_cases is always 0 in v0.1.",
        },
        "counts": dict(counts),
        "total_findings": len(findings),
        "redactions": dict(redactions),
        "warnings": warnings,
        "findings": findings,
        "cases": cases,
    }
