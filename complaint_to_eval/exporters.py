"""Output formats. Every format repeats the provenance and honesty header."""

from __future__ import annotations

import json

from .taxonomy import FAILURE_MODES


def to_json(report: dict) -> str:
    return json.dumps(report, ensure_ascii=False, indent=2)


def to_promptfoo_candidates(report: dict) -> dict:
    """Review-friendly staging format. NOT a runnable promptfoo config.

    A human must pick cases and copy them into promptfooconfig.yaml. Shipping
    unreviewed candidates straight into CI would be exactly the mistake this
    project exists to prevent.
    """
    return {
        "format": "promptfoo-test-candidates",
        "note": (
            "NOT a promptfoo config. Every test is an unreviewed candidate. "
            "Review, edit, then copy individual tests into promptfooconfig.yaml."
        ),
        "dataset": report["dataset"],
        "tests": [
            {
                "description": f"[{case['failure_mode']}] {case['id']} (candidate)",
                "vars": {"input": case["input"]},
                "assert": [
                    {
                        "type": "llm-rubric",
                        "value": (
                            "The response must not exhibit failure mode "
                            f"'{case['failure_mode']}': "
                            f"{FAILURE_MODES[case['failure_mode']]}."
                        ),
                    }
                ],
                "status": "candidate",
                "evidence_record_id": case["evidence_record_id"],
            }
            for case in report["cases"]
        ],
    }


def to_markdown(report: dict) -> str:
    dataset = report["dataset"]
    honesty = report["honesty"]
    lines: list[str] = [
        "# complaint-to-eval report",
        "",
        f"- Dataset: `{dataset['label']}` ({dataset['records']} records)",
        f"- Provenance: **{dataset['provenance']}**",
        f"- Taxonomy: `{report['taxonomy_version']}` (draft)",
        f"- Candidate cases: **{honesty['candidate_cases']}**",
        f"- Accepted (human-reviewed) cases: **{honesty['accepted_cases']}**",
        "",
        "## Read this before quoting any number",
        "",
    ]
    for warning in report["warnings"]:
        lines.append(f"> {warning}")
        lines.append("")
    lines += [
        "## Failure modes (candidate findings)",
        "",
        "| Mode | Meaning | Candidates |",
        "| --- | --- | ---: |",
    ]
    for mode, description in FAILURE_MODES.items():
        lines.append(f"| `{mode}` | {description} | {report['counts'].get(mode, 0)} |")
    lines += ["", "## Evidence samples", ""]
    for finding in report["findings"][:5]:
        lines += [
            f"- **{finding['failure_mode']}** · `{finding['record_id']}` · "
            f"matched `{finding['matched_phrase']}` ({finding['strength']})",
            f"  > {finding['evidence']['quote']}",
        ]
    if not report["findings"]:
        lines.append("No candidates found.")
    if report["redactions"]:
        lines += ["", "## Redactions", ""]
        for kind, count in sorted(report["redactions"].items()):
            lines.append(f"- `{kind}`: {count}")
        lines.append("")
        lines.append("All quotes above refer to redacted text.")
    lines += [
        "",
        "---",
        "",
        "Generated by `complaint-to-eval` · deterministic · no model calls · MIT",
        "",
    ]
    return "\n".join(lines)
